---- LESSON 4: SHARING DATA WITH OTHER ACCOUNTS ----

--1) Create new warehouse

USE ROLE sysadmin;

CREATE WAREHOUSE acme_wh WITH 
    WAREHOUSE_SIZE = 'XSMALL' 
    WAREHOUSE_TYPE = 'STANDARD' 
    AUTO_SUSPEND = 600--600 seconds/10mins
    AUTO_RESUME = TRUE;
    
USE WAREHOUSE acme_wh;

SHOW USERS LIKE 'ACME_ADMIN';
ALTER USER ACME_ADMIN
SET DISPLAY_NAME = 'ACME Car Dealer';

